import assert from 'node:assert/strict';

globalThis.matchMedia = () => ({ matches: true });
const { MobileResolutionBudget, mobilePerformance } = await import('../src/mobile-performance.js');
assert.equal(mobilePerformance, true);
const budget = new MobileResolutionBudget();
for (let i = 0; i < 80; i++) budget.sample(.06);
assert.equal(budget.ratio, .9, 'Initial loading must not trigger resolution churn');
for (let i = 0; i < 400; i++) budget.sample(.06);
assert.equal(budget.ratio, .65, 'Sustained slow rendering should reach the lower bound');
for (let i = 0; i < 180; i++) budget.sample(1 / 30);
assert.equal(budget.ratio, .65, 'Recovery must wait for sustained spare capacity');
for (let i = 0; i < 3000; i++) budget.sample(1 / 30);
assert.equal(budget.ratio, 1, 'Stable rendering should recover, but never exceed the mobile cap');
const severe = new MobileResolutionBudget();
for (let i = 0; i < 200; i++) severe.sample(.3);
assert.equal(severe.ratio, .65, 'Very slow devices must also be able to reduce resolution');
globalThis.matchMedia = () => ({ matches: false });
const desktop = await import('../src/mobile-performance.js?desktop-test');
assert.equal(desktop.mobilePerformance, false, 'Desktop must not enter mobile mode');
console.log('PASS: mobile detection, warmup, slow/severe adaptation, recovery hysteresis and bounds');
