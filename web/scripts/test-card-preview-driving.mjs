import assert from 'node:assert/strict';
import * as THREE from 'three';
globalThis.location={pathname:'/mobile/'};
globalThis.matchMedia=()=>({matches:true});
globalThis.document={hidden:false};
let next=0;const queued=new Map();
globalThis.requestAnimationFrame=fn=>{queued.set(++next,fn);return next;};
globalThis.cancelAnimationFrame=id=>queued.delete(id);
const {PokemonCardScene}=await import('../src/card/pokemon-card-scene.js');
const card=Object.create(PokemonCardScene.prototype);
Object.assign(card,{clock:{getDelta:()=>1/60},elapsed:0,reducedMotion:{matches:false},current:new THREE.Vector2(),target:new THREE.Vector2(),particles:{rotation:{z:0}},updatePortraitView(){},character:{shiny:true},scene:{},camera:{}});
let updates=0,seconds=0,renders=0;
card.mixer={update(dt){updates++;seconds+=dt;}};
card.studioEffect={render(){renders++;}};
card.tick=card.tick.bind(card);card.frame=requestAnimationFrame(card.tick);
card.setExternalDriving(true);assert.equal(queued.size,0);
for(let i=0;i<15;i++)card.renderFrame(1/15);
assert.equal(renders,15);assert.equal(updates,15);assert(Math.abs(seconds-1)<1e-6);
card.onVisibilityChange();card.tick();assert.equal(queued.size,0);assert.equal(renders,15,'hidden preview must not create a second render loop');
card.setExternalDriving(false);assert.equal(queued.size,1,'expanded card resumes one render loop');
card.setExternalDriving(false);assert.equal(queued.size,1,'resuming twice must not duplicate RAF');
console.log('PASS: preview has one driver, continuous animation timing and one render loop after handoff');
